"""Generate static Pydantic wire models from the unchanged OpenAPI snapshot.

Run with Python 3.14: python tools/generate_wire.py
Only this development tool reads OpenAPI. Runtime imports never load the spec.
"""

import json
import keyword
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS: dict[str, Any] = json.loads((ROOT / "contracts/openapi.json").read_text())["components"][
    "schemas"
]


def snake(value: str) -> str:
    value = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", value)
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    value = re.sub(r"[^a-zA-Z0-9]+", "_", value).strip("_").lower()
    if value[:1].isdigit():
        value = "value_" + value
    return value + "_" if keyword.iskeyword(value) else value


def class_name(value: str) -> str:
    return "".join(x[:1].upper() + x[1:] for x in re.split(r"[^a-zA-Z0-9]+", value) if x)


NAMES = {key: class_name(key) for key in SCHEMAS}
assert len(set(NAMES.values())) == len(NAMES)
OBJECTS: dict[str, Any] = {}


def annotation(schema: dict[str, Any], inline_name: str) -> str:
    if "$ref" in schema:
        return NAMES[schema["$ref"].rsplit("/", 1)[-1]]
    if "allOf" in schema:
        assert len(schema["allOf"]) == 1
        return annotation(schema["allOf"][0], inline_name)
    if schema.get("format") == "date-time":
        return "AwareDatetime"
    if schema.get("type") == "string" and schema.get("format") in {"int64", "uint64"}:
        return "UInt64String" if schema["format"] == "uint64" else "Int64String"
    kind = schema.get("type", "object")
    if kind == "array":
        return f"list[{annotation(schema['items'], inline_name + 'Item')}]"
    if kind == "object":
        if schema.get("properties"):
            OBJECTS.setdefault(inline_name, schema)
            return inline_name
        extra = schema.get("additionalProperties")
        value = annotation(extra, inline_name + "Value") if isinstance(extra, dict) else "Any"
        return f"dict[str, {value}]"
    return {
        "string": "StrictStr",
        "integer": "StrictInt",
        "boolean": "StrictBool",
        "number": "Decimal",
    }[kind]


def generate() -> str:
    lines = [
        '"""Generated by tools/generate_wire.py; do not edit manually."""',
        "from decimal import Decimal",
        "from enum import StrEnum",
        "from typing import Any, ClassVar",
        "from pydantic import AwareDatetime, Field, StrictBool, StrictInt, StrictStr",
        "from .wire_base import WireModel, OpenValue, Int64String, UInt64String",
        "",
        "class OpenEnum(StrEnum):",
        "    @classmethod",
        "    def _missing_(cls, value: object) -> Any:",
        "        if not isinstance(value, str):",
        "            return None",
        "        member = str.__new__(cls, value)",
        '        member._name_ = f"UNKNOWN_{value}"',
        "        member._value_ = value",
        "        return member",
        "",
    ]
    for name, schema in SCHEMAS.items():
        cname = NAMES[name]
        if "enum" in schema:
            lines.append(f"class {cname}(OpenEnum):")
            values = list(dict.fromkeys(schema["enum"]))
            for value in values:
                member = snake(str(value)).upper() or "EMPTY"
                lines.append(f"    {member} = {value!r}")
            lines.append("")
        elif not schema:
            lines.extend([f"class {cname}(OpenValue):", "    pass", ""])
        else:
            OBJECTS[cname] = schema
    done: set[str] = set()
    while set(OBJECTS) - done:
        for cname in list(OBJECTS):
            if cname in done:
                continue
            done.add(cname)
            schema = OBJECTS[cname]
            lines.append(f"class {cname}(WireModel):")
            props = schema.get("properties", {})
            nullable = [snake(k) for k, v in props.items() if v.get("nullable")]
            lines.append(
                f"    _nullable_fields: ClassVar[frozenset[str]] = frozenset({nullable!r})"
            )
            for key, field in props.items():
                name = snake(key)
                t = annotation(field, cname + class_name(key))
                # Explicit upstream allowance for JSON numbers on offer price requests.
                if (
                    cname in {"Marketplacev2CreateOfferRequest", "Marketplacev2UpdateOfferRequest"}
                    and key == "priceCents"
                ):
                    t = "StrictStr | StrictInt"
                required = key in schema.get("required", [])
                if not required or field.get("nullable"):
                    t += " | None"
                default = "..." if required else "None"
                hidden = any(x in name for x in ["token", "api_key", "email", "trade_url"])
                options = [f"alias={key!r}", f"repr={not hidden!r}"]
                if field.get("description"):
                    options.append(f"description={field['description']!r}")
                lines.append(f"    {name}: {t} = Field({default}, {', '.join(options)})")
            lines.append("")
    lines.extend(["# Resolve forward references after all named and inline models exist.", ""])
    for cname in OBJECTS:
        lines.append(f"{cname}.model_rebuild()")
    lines.append(
        "\nSCHEMA_MODELS: dict[str, type[WireModel] | type[OpenEnum] | type[OpenValue]] = {"
    )
    lines.extend(f"    {name!r}: {cname}," for name, cname in NAMES.items())
    lines.extend(["}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    (ROOT / "src/dmarket_client/_internal/wire.py").write_text(generate())
    print(f"Generated {len(NAMES)} named schemas and inline objects")
